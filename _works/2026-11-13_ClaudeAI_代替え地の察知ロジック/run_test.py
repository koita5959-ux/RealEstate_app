"""
代替え提案 察知ロジックのテスト。
各ケース: (名前, 客の発話リスト, 物件, 期待する判定, 区分)
  区分 "基本" … ルールで取れて当然のもの
  区分 "難"   … 言い回しが遠回しで、ルールの限界を測るためのもの
"""

from detector import detect, Property

LAND = Property(land_only=True)
OLD = Property(land_only=False, house_age=28)
NEW = Property(land_only=False, house_age=8)

CASES = [
    # ---- 発動すべき（基本） ----
    ("住み替え＋手狭", ["子どもが増えて家が手狭なんです", "今の土地を売って住み替えも考えてます"], LAND, "発動", "基本"),
    ("相続地＋郊外OK", ["親から相続した土地があって", "郊外でもいいので広いところに住みたい"], LAND, "発動", "基本"),
    ("築古＋二世帯", ["家はもう築30年近くです", "親と同居したいので、ここを売って二世帯にできる場所を"], OLD, "発動", "基本"),
    ("売却額＋庭", ["この土地いくらで売れますか", "庭のある家にしたくて"], LAND, "発動", "基本"),
    ("畑がしたい", ["定年後は畑をやりたい", "ここを手放して田舎に行くのもありかなと"], LAND, "発動", "基本"),
    ("車2台＋少し離れ", ["車がもう1台増えるんですが駐車場がなくて", "少し離れてもいいから買い替えたい"], LAND, "発動", "基本"),
    ("築浅だが建て替え前提", ["築8年ですが建物にはこだわらないです", "売って、もっと広い土地を探したい"], NEW, "発動", "基本"),

    # ---- 発動すべきでない（基本） ----
    ("駅近志向", ["手狭なので住み替えたいけど", "駅近は絶対に譲れません"], LAND, "不発", "基本"),
    ("地元を離れたくない", ["売って広い家にしたいけど", "今の場所からは離れたくないです"], LAND, "不発", "基本"),
    ("売る気なし", ["売るつもりはないです", "ただ庭をもう少し広くできないかなと"], LAND, "保留", "基本"),
    ("築浅・こだわりあり", ["築8年の家です", "売って広い土地に住み替えたい"], NEW, "対象外", "基本"),
    ("単なる相場確認", ["このあたりの相場を知りたいだけです"], LAND, "不発", "基本"),
    ("広さだけ", ["もっと広い家に住みたいなあ"], LAND, "保留", "基本"),
    ("売却だけ", ["この土地を売却したいです", "査定をお願いできますか"], LAND, "保留", "基本"),
    ("学区固定", ["住み替えで庭付きの家が欲しいけど", "学区は変えたくないんです"], LAND, "不発", "基本"),

    # ---- 難（遠回しな言い方：ルールの限界を測る） ----
    ("遠回し：走り回れる", ["子どもが思いっきり走り回れる環境が欲しくて", "ここを手放すのも選択肢です"], LAND, "発動", "難"),
    ("遠回し：のびのび", ["もっとのびのび暮らしたい", "今の家は処分してもいい"], LAND, "発動", "難"),
    ("遠回し：犬", ["大型犬を飼いたいんですが今の家じゃ無理で", "売ってもいいと思ってます"], LAND, "発動", "難"),
    ("遠回し：駅距離の気にしなさ", ["車移動なので駅はどうでもいい", "ここを売って広いところへ"], LAND, "発動", "難"),
    ("否定の取り違え", ["駅近じゃなくてもいいです", "売って広い家に"], LAND, "発動", "難"),
    ("他人の話", ["友人が郊外に住み替えたそうで", "うちは売る予定はないですけど"], LAND, "不発", "難"),
]


def main():
    ok = {"基本": 0, "難": 0}
    total = {"基本": 0, "難": 0}
    misses = []
    print(f"{'判定':<4} {'区分':<3} {'期待':<4} {'結果':<4} {'点':>3}  ケース")
    print("-" * 70)
    for name, utts, prop, expected, kind in CASES:
        r = detect(utts, prop)
        total[kind] += 1
        good = r.decision == expected
        ok[kind] += good
        mark = "○" if good else "×"
        print(f"{mark:<4} {kind:<3} {expected:<4} {r.decision:<4} {r.score:>3}  {name}  目的={r.purposes}")
        if not good:
            misses.append((name, expected, r))
    print("-" * 70)
    for k in ("基本", "難"):
        print(f"{k}: {ok[k]}/{total[k]}")
    if misses:
        print("\n外れの詳細:")
        for name, exp, r in misses:
            hits = {k: [h[0] for h in v] for k, v in r.hits.items()}
            print(f"- {name}: 期待={exp} 結果={r.decision}（{r.reason}） 拾った語={hits}")


if __name__ == "__main__":
    main()
